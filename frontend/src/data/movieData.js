// Get movie by ID
export const getMovieById = (id) => {
  const numericId = parseInt(id);
  
  // Check regular movies
  const movie = allMovies.find(m => m.id === numericId);
  if (movie) return movie;
  
  // Check coming soon movies
  const comingSoonMovie = comingSoonMovies.find(m => m.id === numericId);
  if (comingSoonMovie) return comingSoonMovie;
  
  // Return featured movie as fallback
  return featuredMovie;
};
